export function TripIcon({
  name,
  size = 18,
  strokeWidth,
  className,
}: {
  name: TripIconName;
  size?: number;
  /** In the icon's own viewBox units, as in the app. */
  strokeWidth?: number;
  className?: string;
}) {
  const icon = ICONS[name];
  // The app's TripIcons default to 1 on their ~16 viewBoxes; the 24-grid
  // stand-ins need 1.5 for the same ~1.1px line.
  const grid24 = icon.viewBox === '0 0 24 24';
  return (
    <svg
      width={size}
      height={size}
      viewBox={icon.viewBox}
      fill="none"
      aria-hidden="true"
      focusable="false"
      className={className}
    >
      <path
        d={icon.d}
        fill="none"
        stroke="currentColor"
        strokeWidth={strokeWidth ?? (grid24 ? 1.5 : 1)}
        strokeLinecap="round"
        strokeLinejoin="round"
      />
    </svg>
  );
}

